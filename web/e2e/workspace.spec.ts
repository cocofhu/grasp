for (const theme of ['light', 'dark']) test(`long settings pages scroll by wheel and retain a visible scrollbar (${theme})`, async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 720 })
  await page.goto(`/workspace.html?view=/settings&theme=${theme}`)
  const scroll = page.getByTestId('shell-page-scroll')
  await expect(page.getByTestId('settings-save-actions')).toBeAttached()
  const layout = await scroll.evaluate(el => ({ client: el.clientHeight, content: el.scrollHeight, color: getComputedStyle(el).scrollbarColor }))
  expect(layout.content).toBeGreaterThan(layout.client)
  expect(layout.color).not.toBe('rgba(0, 0, 0, 0) rgba(0, 0, 0, 0)')
  await page.mouse.move(1340, 500)
  await page.mouse.wheel(0, 4000)
  await expect(page.getByTestId('settings-save-actions')).toBeInViewport()
  await page.mouse.move(10, 10)
  await expect.poll(() => scroll.evaluate(el => el.classList.contains('is-scrolling'))).toBe(false)
  const idleColor = await scroll.evaluate(el => getComputedStyle(el).scrollbarColor)
  expect(idleColor).not.toBe('rgba(0, 0, 0, 0) rgba(0, 0, 0, 0)')
  await page.setViewportSize({ width: 390, height: 640 })
  await scroll.evaluate(el => { el.scrollTop = 0 })
  await page.mouse.move(280, 400)
  await page.mouse.wheel(0, 8000)
  await expect(page.getByTestId('settings-save-actions')).toBeInViewport()
})

