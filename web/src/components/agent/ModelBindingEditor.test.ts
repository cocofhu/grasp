// @vitest-environment happy-dom
import { mount, flushPromises } from '@vue/test-utils'
import { createI18n } from 'vue-i18n'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import ModelBindingEditor from './ModelBindingEditor.vue'
import AppSelect from '@/components/ui/AppSelect.vue'
import type { ModelBinding } from '@/lib/api/api'
import common from '@/locales/en/common.json'
const mocks = vi.hoisted(() => ({ keys: vi.fn(), connections: vi.fn(), configurations: vi.fn(), capabilities: vi.fn(), defaults: vi.fn() }))
vi.mock('@/lib/api/api', () => ({ api: { listCredentials: mocks.keys, listModelConnections: mocks.connections, listModelConfigurations: mocks.configurations, listToolCapabilities: mocks.capabilities, getModelDefaults: mocks.defaults } }))
const key = { id: 'key', type: 'ai', name: 'Reusable API key', purpose: 'model_api', issuer: 'deepseek', configured: true }
const connection = { id: 'service', name: 'DeepSeek service', providerId: 'deepseek', protocol: 'anthropic-messages', baseUrl: 'https://api.deepseek.com/anthropic', credentialId: 'key', auth: { scheme: 'bearer' }, models: [{ id: 'upstream/model-v1', source: 'manual' }, { id: 'fast-v1', source: 'manual' }], state: 'active', revision: 1 }
function setup(backend = 'claude_code', binding: ModelBinding = { kind: 'inherit' }, options: { compact?: boolean; allowInherit?: boolean; configurationsOnly?: boolean } = {}) { return mount(ModelBindingEditor, { props: { backend, modelValue: binding, ...options }, global: { plugins: [createI18n({ legacy: false, locale: 'en', messages: { en: common } })], stubs: { RouterLink: true, CliModelSelect: true, Teleport: true }, directives: { 'hover-ink': {} } } }) }
async function pick(wrapper: ReturnType<typeof setup>, testId: string, value: string, query?: string) {
  const select = wrapper.get(`[data-testid="${testId}"]`)
  const trigger = select.get('[data-test="app-select-trigger"]')
  if (trigger.attributes('aria-expanded') !== 'true') await trigger.trigger('click')
  if (query !== undefined) await select.get('[data-test="app-select-search"]').setValue(query)
  await select.get(`[data-test="app-select-option-${value}"]`).trigger('click')
}
beforeEach(() => {
  mocks.keys.mockResolvedValue({ items: [key, { id: 'cursor', type: 'ai', name: 'Cursor', purpose: 'tool_auth', toolId: 'cursor', configured: true }] })
  mocks.connections.mockResolvedValue({ items: [connection] })
  mocks.capabilities.mockResolvedValue({ items: [{ toolId: 'claude_code', modes: ['platform', 'connection'], protocols: ['anthropic-messages'], roleNames: ['main', 'fast', 'subagent'], adapterState: 'existing' }, { toolId: 'cursor', modes: ['platform'], protocols: [], adapterState: 'existing' }] })
  mocks.defaults.mockResolvedValue({ bindingsByBackend: {} })
  mocks.configurations.mockResolvedValue({ items: [] })
})
describe('ModelBindingEditor', () => {
  const configuration = { id: 'profile', name: 'Team Claude', backend: 'claude_code', binding: { kind: 'connection', connectionId: 'service', modelId: 'upstream/model-v1' }, state: 'active', revision: 1 }
  it('shows only the searchable named-model picker and requires an explicit configuration even when a workspace default exists', async () => {
    mocks.configurations.mockResolvedValue({ items: [configuration, { ...configuration, id: 'disabled', state: 'disabled' }, { ...configuration, id: 'other-tool', backend: 'cursor' }] })
    mocks.defaults.mockResolvedValue({ bindingsByBackend: { claude_code: { kind: 'configuration', configurationId: 'profile' } } })
    const wrapper = setup('claude_code', { kind: 'inherit' }, { compact: true, configurationsOnly: true }); await flushPromises()
    expect(wrapper.find('h3').exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-configuration"]').exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-inherit"]').exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-advanced"]').exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-inherited"]').exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-problem"]').exists()).toBe(false)
    expect(wrapper.findComponent({ name: 'RouterLink' }).exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-configuration-summary"]').exists()).toBe(false)
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([false])
    const field = wrapper.get('[data-testid="model-binding-configuration-select"]')
    await field.get('[data-test="app-select-trigger"]').trigger('click')
    expect(field.findAll('[role="option"]').map((option) => option.text())).toEqual(['Team Claude'])
    await pick(wrapper, 'model-binding-configuration-select', 'profile', 'Team')
    expect(wrapper.emitted('update:modelValue')).toEqual([[{ kind: 'configuration', configurationId: 'profile' }]])
    await wrapper.setProps({ modelValue: { kind: 'configuration', configurationId: 'profile' } })
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([true])
    expect(wrapper.find('[data-testid="model-binding-configuration-summary"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('keeps an empty configuration-only picker empty and rejects ids outside its active tool options', async () => {
    const wrapper = setup('claude_code', { kind: 'configuration', configurationId: '' }, { configurationsOnly: true }); await flushPromises()
    const field = wrapper.getComponent(AppSelect)
    expect(field.get('[data-test="app-select-trigger"]').text()).toContain('No active model configuration is available for this tool.')
    await field.get('[data-test="app-select-trigger"]').trigger('click')
    expect(field.get('[data-test="app-select-empty"]').text()).toBe('No active model configuration is available for this tool.')
    expect(field.find('[role="option"]').exists()).toBe(false)
    for (const value of ['', '__inherit', 'disabled', 'other-tool', 'missing']) field.vm.$emit('update:modelValue', value)
    await flushPromises()
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([false])
    wrapper.unmount()
  })
  it('retains unavailable configuration references and never falls back after switching tools', async () => {
    const cursorConfiguration = { ...configuration, id: 'cursor-profile', name: 'Cursor team', backend: 'cursor', binding: { kind: 'platform', credentialId: 'cursor' } }
    mocks.configurations.mockResolvedValue({ items: [configuration, cursorConfiguration] })
    const wrapper = setup('claude_code', { kind: 'configuration', configurationId: 'deleted-profile' }, { compact: true, configurationsOnly: true }); await flushPromises()
    expect(wrapper.get('[data-test="app-select-trigger"]').text()).toContain('deleted-profile')
    expect(wrapper.get('[data-test="app-select-trigger"]').attributes('aria-invalid')).toBe('true')
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    await wrapper.setProps({ modelValue: { kind: 'configuration', configurationId: 'profile' } })
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([true])
    await wrapper.setProps({ backend: 'cursor' })
    expect(wrapper.get('[data-test="app-select-trigger"]').text()).toContain('Team Claude')
    expect(wrapper.get('[data-test="app-select-trigger"]').attributes('aria-invalid')).toBe('true')
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([false])
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    await pick(wrapper, 'model-binding-configuration-select', 'cursor-profile', 'Cursor')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toEqual({ kind: 'configuration', configurationId: 'cursor-profile' })
    await wrapper.setProps({ modelValue: { kind: 'configuration', configurationId: 'cursor-profile' } })
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([true])
    wrapper.unmount()
  })
  it('invalidates a named model whose key was revoked without exposing direct source controls', async () => {
    mocks.configurations.mockResolvedValue({ items: [configuration] })
    mocks.keys.mockResolvedValue({ items: [{ ...key, configured: false }] })
    const wrapper = setup('claude_code', { kind: 'configuration', configurationId: 'profile' }, { configurationsOnly: true }); await flushPromises()
    expect(wrapper.get('[data-test="app-select-trigger"]').attributes('aria-invalid')).toBe('true')
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([false])
    expect(wrapper.find('[data-testid="model-binding-advanced"]').exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-problem"]').exists()).toBe(false)
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    wrapper.unmount()
  })
  it('retains a real request error and retry when configured to show only saved models', async () => {
    mocks.configurations.mockRejectedValueOnce(new Error('models unavailable'))
    const wrapper = setup('claude_code', { kind: 'configuration', configurationId: '' }, { configurationsOnly: true }); await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('models unavailable')
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([false])
    await wrapper.get('[role="alert"] button').trigger('click'); await flushPromises()
    expect(wrapper.find('[role="alert"]').exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-configuration-select"]').exists()).toBe(true)
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    wrapper.unmount()
  })
  it('shows one searchable compact picker immediately and maps explicit configuration and inheritance selections', async () => {
    mocks.configurations.mockResolvedValue({ items: [configuration] })
    const wrapper = setup('claude_code', { kind: 'inherit' }, { compact: true }); await flushPromises()
    expect(wrapper.find('h3').exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-configuration"]').exists()).toBe(false)
    expect(wrapper.find('[data-testid="model-binding-inherit"]').exists()).toBe(false)
    expect(wrapper.get('[data-testid="model-binding-configuration-select"] [data-test="app-select-trigger"]').text()).toContain('Workspace default')
    expect(wrapper.find('[data-testid="model-binding-inherited"]').exists()).toBe(false)
    expect(wrapper.findAll('[data-testid="model-binding-problem"]')).toHaveLength(1)
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    await pick(wrapper, 'model-binding-configuration-select', 'profile', 'Team')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toEqual({ kind: 'configuration', configurationId: 'profile' })
    await wrapper.setProps({ modelValue: { kind: 'configuration', configurationId: 'profile' } })
    expect(wrapper.get('[data-testid="model-binding-configuration-summary"]').text()).toContain('upstream/model-v1')
    await pick(wrapper, 'model-binding-configuration-select', '__inherit', 'Workspace')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toEqual({ kind: 'inherit' })
    expect(wrapper.get('[data-testid="model-binding-advanced"]').element.tagName).toBe('DETAILS')
    wrapper.unmount()
  })
  it('retains a compact inherited default summary without replacing its binding', async () => {
    mocks.configurations.mockResolvedValue({ items: [configuration] })
    mocks.defaults.mockResolvedValue({ bindingsByBackend: { claude_code: { kind: 'configuration', configurationId: 'profile' } } })
    const wrapper = setup('claude_code', { kind: 'inherit' }, { compact: true }); await flushPromises()
    expect(wrapper.get('[data-testid="model-binding-inherited"]').text()).toContain('Team Claude')
    expect(wrapper.get('[data-testid="model-binding-configuration-select"] [data-test="app-select-trigger"]').text()).toContain('Workspace default')
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([true])
    wrapper.unmount()
  })
  it('keeps an unavailable compact reference visible and never substitutes inheritance or another configuration', async () => {
    mocks.configurations.mockResolvedValue({ items: [configuration] })
    const wrapper = setup('claude_code', { kind: 'configuration', configurationId: 'deleted-profile' }, { compact: true, allowInherit: false }); await flushPromises()
    const field = wrapper.get('[data-testid="model-binding-configuration-select"]')
    expect(field.get('[data-test="app-select-trigger"]').text()).toContain('deleted-profile')
    expect(field.get('[data-test="app-select-trigger"]').attributes('aria-invalid')).toBe('true')
    await field.get('[data-test="app-select-trigger"]').trigger('click')
    expect(field.find('[data-test="app-select-option-__inherit"]').exists()).toBe(false)
    expect(field.get('[data-test="app-select-option-profile"]').exists()).toBe(true)
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([false])
    wrapper.unmount()
  })
  it('offers only active configurations for the current tool and saves only their reference', async () => {
    mocks.configurations.mockResolvedValue({ items: [configuration, { ...configuration, id: 'other-tool', name: 'Other tool', backend: 'cursor' }, { ...configuration, id: 'disabled', name: 'Disabled profile', state: 'disabled' }] })
    const wrapper = setup('claude_code', { kind: 'configuration', configurationId: '' }); await flushPromises()
    const select = wrapper.get('[data-testid="model-binding-configuration-select"]')
    await select.get('[data-test="app-select-trigger"]').trigger('click')
    expect(select.text()).toContain('Team Claude')
    expect(select.text()).not.toContain('Other tool')
    expect(select.text()).not.toContain('Disabled profile')
    await pick(wrapper, 'model-binding-configuration-select', 'profile', 'Team')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toEqual({ kind: 'configuration', configurationId: 'profile' })
    await wrapper.setProps({ modelValue: { kind: 'configuration', configurationId: 'profile' } })
    expect(wrapper.get('[data-testid="model-binding-configuration-summary"]').text()).toContain('Reusable API key')
    expect(wrapper.get('[data-testid="model-binding-configuration-summary"]').text()).toContain('upstream/model-v1')
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([true])
    expect(wrapper.find('[data-testid="model-binding-model"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('reports unavailable or mismatched configurations without changing the selected tool or reference', async () => {
    mocks.configurations.mockResolvedValue({ items: [configuration] })
    const wrapper = setup('claude_code', { kind: 'configuration', configurationId: 'deleted-profile' }); await flushPromises()
    expect(wrapper.get('[data-testid="model-binding-problem"]').text()).toContain('missing or disabled')
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([false])
    await wrapper.setProps({ backend: 'cursor', modelValue: { kind: 'configuration', configurationId: 'profile' } })
    expect(wrapper.get('[data-testid="model-binding-problem"]').text()).toContain('different coding tool')
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    expect(wrapper.get('[data-testid="model-binding-configuration-select"]').text()).toContain('Team Claude')
    wrapper.unmount()
  })
  it('expands a configuration inherited through the current tool default', async () => {
    mocks.configurations.mockResolvedValue({ items: [configuration] })
    mocks.defaults.mockResolvedValue({ bindingsByBackend: { claude_code: { kind: 'configuration', configurationId: 'profile' } } })
    const wrapper = setup(); await flushPromises()
    expect(wrapper.get('[data-testid="model-binding-inherited"]').text()).toContain('Team Claude')
    expect(wrapper.get('[data-testid="model-binding-inherited"]').text()).toContain('upstream/model-v1')
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([true])
    wrapper.unmount()
  })
  it('validates the referenced credential and keeps direct defaults editing available', async () => {
    mocks.configurations.mockResolvedValue({ items: [configuration] })
    mocks.keys.mockResolvedValue({ items: [{ ...key, configured: false }] })
    const wrapper = setup('claude_code', { kind: 'configuration', configurationId: 'profile' }); await flushPromises()
    expect(wrapper.get('[data-testid="model-binding-problem"]').text()).toContain('key is missing')
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([false])
    await wrapper.setProps({ directOnly: true, modelValue: { kind: 'platform', credentialId: '' } })
    expect(wrapper.find('[data-testid="model-binding-configuration"]').exists()).toBe(false)
    expect(wrapper.get('[data-testid="model-binding-platform"]').exists()).toBe(true)
    expect(wrapper.get('[data-testid="model-binding-advanced"]').element.tagName).toBe('DIV')
    wrapper.unmount()
  })
  it('shows a missing default for the current tool without switching it', async () => { const wrapper = setup(); await flushPromises(); expect(wrapper.text()).toContain('This tool has no workspace default'); expect(wrapper.emitted('update:modelValue')).toBeUndefined(); wrapper.unmount() })
  it('never offers Cursor third-party connections and uses only its own platform authorization', async () => {
    const wrapper = setup('cursor', { kind: 'platform', credentialId: 'cursor' }); await flushPromises()
    expect(wrapper.get('[data-testid="model-binding-connection"]').attributes('disabled')).toBeDefined()
    await wrapper.get('[data-testid="model-binding-credential"] [data-test="app-select-trigger"]').trigger('click')
    expect(wrapper.get('[data-testid="model-binding-credential"]').text()).toContain('Cursor')
    expect(wrapper.get('[data-testid="model-binding-credential"]').text()).not.toContain('Reusable API key')
    const modelSelect = wrapper.findComponent({ name: 'CliModelSelect' })
    expect(modelSelect.props('hideCommand')).toBe(true)
    expect(modelSelect.props('hideAutoSub')).toBe(true)
    wrapper.unmount()
  })
  it('uses raw model IDs and keeps auxiliary models within the selected connection', async () => {
    const wrapper = setup('claude_code', { kind: 'connection', connectionId: 'service', modelId: 'upstream/model-v1' }); await flushPromises()
    await pick(wrapper, 'model-binding-role-subagent', 'fast-v1', 'fast')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toEqual({ kind: 'connection', connectionId: 'service', modelId: 'upstream/model-v1', toolSettings: { modelRoles: { subagent: 'fast-v1' } } })
    await pick(wrapper, 'model-binding-connection-select', '')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toEqual({ kind: 'connection', connectionId: '', modelId: '' })
    wrapper.unmount()
  })
  it('searches branded service models by their raw IDs and preserves the selection when its service is reselected', async () => {
    mocks.connections.mockResolvedValue({ items: [{ ...connection, models: [{ id: 'vendor/raw/main', name: 'Main model', source: 'manual' }, { id: 'vendor/raw/fast', name: 'Fast model', source: 'manual' }] }] })
    const wrapper = setup('claude_code', { kind: 'connection', connectionId: 'service', modelId: 'vendor/raw/main' }); await flushPromises()
    expect(wrapper.find('select').exists()).toBe(false)
    expect(wrapper.get('[data-testid="model-binding-model"] [data-provider-logo="deepseek"]').attributes('aria-hidden')).toBe('true')
    await pick(wrapper, 'model-binding-model', 'vendor/raw/fast', 'raw/fast')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toEqual({ kind: 'connection', connectionId: 'service', modelId: 'vendor/raw/fast' })
    await wrapper.setProps({ modelValue: { kind: 'connection', connectionId: 'service', modelId: 'vendor/raw/fast', toolSettings: { modelRoles: { fast: 'vendor/raw/main' } } } })
    const changes = wrapper.emitted('update:modelValue')?.length
    await pick(wrapper, 'model-binding-connection-select', 'service', 'DeepSeek')
    expect(wrapper.emitted('update:modelValue')?.length).toBe(changes)
    expect(wrapper.get('[data-testid="model-binding-model"] [data-test="app-select-trigger"]').text()).toContain('Fast model')
    wrapper.unmount()
  })
  it('shows missing credential, service and model references without selecting an available replacement', async () => {
    mocks.keys.mockResolvedValue({ items: [key, { id: 'cursor', type: 'ai', name: 'Revoked Cursor', purpose: 'tool_auth', toolId: 'cursor', configured: false }] })
    const wrapper = setup('cursor', { kind: 'platform', credentialId: 'cursor' }); await flushPromises()
    expect(wrapper.get('[data-testid="model-binding-credential"] [data-test="app-select-trigger"]').text()).toContain('Revoked Cursor')
    expect(wrapper.get('[data-testid="model-binding-credential"] [data-test="app-select-trigger"]').attributes('aria-invalid')).toBe('true')
    await wrapper.setProps({ backend: 'claude_code', modelValue: { kind: 'connection', connectionId: 'deleted-service', modelId: 'old/model' } })
    expect(wrapper.get('[data-testid="model-binding-connection-select"] [data-test="app-select-trigger"]').text()).toContain('deleted-service')
    await wrapper.setProps({ modelValue: { kind: 'connection', connectionId: 'service', modelId: 'deleted/model' } })
    expect(wrapper.get('[data-testid="model-binding-model"] [data-test="app-select-trigger"]').text()).toContain('deleted/model')
    expect(wrapper.get('[data-testid="model-binding-model"] [data-test="app-select-trigger"]').attributes('aria-invalid')).toBe('true')
    expect(wrapper.emitted('update:modelValue')).toBeUndefined()
    expect(wrapper.emitted('validity')?.at(-1)).toEqual([false])
    wrapper.unmount()
  })
  it('searches adapted route profiles and keeps their original values in the binding', async () => {
    mocks.connections.mockResolvedValue({ items: [{ ...connection, auth: { scheme: 'x-api-key' } }] })
    mocks.capabilities.mockResolvedValue({ items: [{ toolId: 'deepseek_harness', modes: ['connection'], protocols: ['anthropic-messages'], routeProfiles: ['deepseek-native'], adapterState: 'existing' }] })
    const wrapper = setup('deepseek_harness', { kind: 'connection', connectionId: 'service', modelId: 'upstream/model-v1' }); await flushPromises()
    await pick(wrapper, 'model-binding-route-profile', 'deepseek-native', 'native')
    expect(wrapper.emitted('update:modelValue')?.at(-1)?.[0]).toEqual({ kind: 'connection', connectionId: 'service', modelId: 'upstream/model-v1', toolSettings: { routeProfile: 'deepseek-native' } })
    await wrapper.setProps({ modelValue: { kind: 'connection', connectionId: 'service', modelId: 'upstream/model-v1', toolSettings: { routeProfile: 'obsolete-route' } } })
    expect(wrapper.get('[data-testid="model-binding-route-profile"] [data-test="app-select-trigger"]').text()).toContain('obsolete-route')
    expect(wrapper.get('[data-testid="model-binding-route-profile"] [data-test="app-select-trigger"]').attributes('aria-invalid')).toBe('true')
    wrapper.unmount()
  })
  it('reports a load failure and retries the real API methods instead of fabricating capabilities', async () => {
    mocks.capabilities.mockRejectedValueOnce(new Error('capabilities unavailable'))
    const wrapper = setup(); await flushPromises(); expect(wrapper.text()).toContain('capabilities unavailable')
    await wrapper.get('button').trigger('click'); await flushPromises(); expect(wrapper.find('[data-testid="model-binding-connection"]').exists()).toBe(true); wrapper.unmount()
  })
})
