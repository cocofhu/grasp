// @vitest-environment happy-dom
import { flushPromises, mount } from '@vue/test-utils'
import { createI18n } from 'vue-i18n'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import type { ModelConnection } from '@/lib/api/api'
import ModelConnectionManager from './ModelConnectionManager.vue'
const mocks = vi.hoisted(() => ({ list: vi.fn(), caps: vi.fn(), create: vi.fn(), update: vi.fn(), remove: vi.fn(), success: vi.fn() }))
vi.mock('@/lib/api/api', () => ({ api: { listModelConnections: mocks.list, listToolCapabilities: mocks.caps, createModelConnection: mocks.create, updateModelConnection: mocks.update, deleteModelConnection: mocks.remove } }))
vi.mock('@/lib/composables/useToast', () => ({ useToast: () => ({ success: mocks.success }) }))
const key = { id: 'key', name: 'Team API key', purpose: 'model_api' as const, type: 'ai', issuer: 'deepseek', configured: true, masked: 'sk-…1234' }
function setup() { return mount(ModelConnectionManager, { props: { credentials: [key] }, global: { plugins: [createI18n({ legacy: false, locale: 'en', messages: { en: {} } })], stubs: { Teleport: true, Icon: true } } }) }
beforeEach(() => { vi.clearAllMocks(); mocks.list.mockResolvedValue({ items: [] }); mocks.caps.mockResolvedValue({ items: [] }); mocks.create.mockResolvedValue({ id: 'new' }); mocks.update.mockResolvedValue({ id: 'existing' }) })
async function chooseProvider(wrapper: ReturnType<typeof setup>, provider: string) {
  wrapper.getComponent('[data-testid="model-connection-provider"]').vm.$emit('update:modelValue', provider)
  await flushPromises()
}
async function chooseCredential(wrapper: ReturnType<typeof setup>, id: string) {
  wrapper.getComponent('[data-testid="model-connection-credential"]').vm.$emit('update:modelValue', id)
  await flushPromises()
}
async function fillForm(wrapper: ReturnType<typeof setup>) {
  await wrapper.get('[data-testid="model-connection-add"]').trigger('click')
  await chooseProvider(wrapper, 'deepseek')
  await wrapper.get('[data-testid="model-connection-name"]').setValue('Independent model service')
  await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
  expect(wrapper.get('[data-testid="model-connection-base-url"]').element).toHaveProperty('value', 'https://api.deepseek.com/v1')
  await chooseCredential(wrapper, 'key')
  await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
}
async function chooseSearchOption(wrapper: ReturnType<typeof setup>, testId: string, value: string) {
  const field = wrapper.get(`[data-testid="${testId}"]`)
  await field.get('[data-test="app-select-trigger"]').trigger('click')
  await field.get('[data-test="app-select-search"]').setValue(value)
  await field.get(`[data-test="app-select-option-${value}"]`).trigger('click')
}

describe('ModelConnectionManager', () => {
  it('keeps unsupported legacy authentication visible until a supported searchable choice is made', async () => {
    const original: ModelConnection = { id: 'existing', name: 'Legacy header service', providerId: 'custom', protocol: 'openai-chat-completions', baseUrl: 'https://model.example/v1', credentialId: key.id, auth: { scheme: 'custom-header', headerName: 'X-Token' }, models: [], state: 'active', revision: 1 }
    mocks.list.mockResolvedValue({ items: [original] })
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-edit-existing"]').trigger('click')
    await chooseSearchOption(wrapper, 'model-connection-protocol', 'openai-responses')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    const field = wrapper.get('[data-testid="model-connection-auth"]')
    expect(field.get('[data-test="app-select-trigger"]').text()).toContain('Custom header · unsupported')
    expect(wrapper.get('[data-testid="model-connection-next"]').attributes('disabled')).toBeDefined()
    await chooseSearchOption(wrapper, 'model-connection-auth', 'bearer')
    expect(wrapper.find('select').exists()).toBe(false)
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.update).toHaveBeenCalledWith(original.id, expect.objectContaining({ protocol: 'openai-responses', auth: { scheme: 'bearer' } }))
    wrapper.unmount()
  })
  it('keeps a customized Base, protocol and authentication when the current provider is selected again', async () => {
    const original: ModelConnection = { id: 'existing', name: 'Customized service', providerId: 'deepseek', protocol: 'anthropic-messages', baseUrl: 'https://proxy.example.test/anthropic', credentialId: key.id, auth: { scheme: 'x-api-key' }, state: 'active', revision: 1, models: [] }
    mocks.list.mockResolvedValue({ items: [original] })
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-edit-existing"]').trigger('click')
    await chooseProvider(wrapper, 'deepseek')
    expect(wrapper.getComponent('[data-testid="model-connection-protocol"]').props('modelValue')).toBe('anthropic-messages')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    expect(wrapper.get('[data-testid="model-connection-base-url"]').element).toHaveProperty('value', original.baseUrl)
    expect(wrapper.getComponent('[data-testid="model-connection-auth"]').props('modelValue')).toBe('x-api-key')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.update).toHaveBeenCalledWith(original.id, expect.objectContaining({ baseUrl: original.baseUrl, protocol: original.protocol, auth: original.auth }))
    wrapper.unmount()
  })

  it('offers searchable credential names and provider logos without exposing masked key details', async () => {
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-add"]').trigger('click')
    await chooseProvider(wrapper, 'deepseek')
    await wrapper.get('[data-testid="model-connection-name"]').setValue('API service')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    const choice = wrapper.get('[data-testid="model-connection-credential"]')
    await choice.get('[data-test="app-select-trigger"]').trigger('click')
    await flushPromises()
    await wrapper.get('[data-test="app-select-search"]').setValue('Team')
    const option = wrapper.get('[data-test="app-select-option-key"]')
    expect(option.text()).toContain(key.name)
    expect(option.text()).not.toContain(key.masked)
    expect(option.find('[data-provider-logo="deepseek"]').exists()).toBe(true)
    await option.trigger('click')
    expect(choice.get('[data-test="app-select-trigger"]').text()).toContain(key.name)
    expect(choice.find('[data-provider-logo="deepseek"]').exists()).toBe(true)
    expect(wrapper.get('[data-testid="model-connection-next"]').attributes('disabled')).toBeUndefined()
    wrapper.unmount()
  })

  it('preserves the latest model directory and metadata when another editor changes it before the service is saved', async () => {
    const original: ModelConnection = { id: 'existing', name: 'Shared service', providerId: 'deepseek', protocol: 'openai-chat-completions', baseUrl: 'https://api.deepseek.com/v1', credentialId: key.id, auth: { scheme: 'bearer' }, state: 'active', revision: 1, models: [{ id: 'original/model', source: 'manual' }] }
    mocks.list.mockResolvedValue({ items: [original] })
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-edit-existing"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-base-url"]').setValue('https://updated.example.test/v1')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    const latestModels = [{ id: 'original/model', source: 'manual' as const, contextWindow: 256000 }, { id: 'added/by-another-editor', source: 'manual' as const, input: ['text', 'image'] as ('text' | 'image')[], maxTokens: 16384 }]
    mocks.list.mockResolvedValue({ items: [{ ...original, models: latestModels, revision: 2 }] })
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.update).toHaveBeenCalledWith(original.id, expect.objectContaining({ baseUrl: 'https://updated.example.test/v1', models: latestModels }))
    wrapper.unmount()
  })

  it('keeps the service draft when its latest directory cannot be read and never submits the stale cache', async () => {
    const original = { id: 'existing', name: 'Shared service', providerId: 'deepseek', protocol: 'openai-chat-completions', baseUrl: 'https://api.deepseek.com/v1', credentialId: key.id, auth: { scheme: 'bearer' }, state: 'active', revision: 1, models: [{ id: 'original/model', source: 'manual' }] }
    mocks.list.mockResolvedValue({ items: [original] })
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-edit-existing"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-base-url"]').setValue('https://updated.example.test/v1')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    mocks.list.mockRejectedValueOnce(new Error('latest directory unavailable'))
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.update).not.toHaveBeenCalled()
    expect(wrapper.text()).toContain('latest directory unavailable')
    expect(wrapper.get('[data-testid="model-connection-form"]').attributes('data-step')).toBe('3')
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.update).toHaveBeenCalledWith(original.id, expect.objectContaining({ baseUrl: 'https://updated.example.test/v1', models: original.models }))
    wrapper.unmount()
  })

  it('also preserves the current directory when toggling a service from a previously loaded row', async () => {
    const original = { id: 'existing', name: 'Shared service', providerId: 'deepseek', protocol: 'openai-chat-completions', baseUrl: 'https://api.deepseek.com/v1', credentialId: key.id, auth: { scheme: 'bearer' }, state: 'active', revision: 1, models: [] }
    mocks.list.mockResolvedValue({ items: [original] })
    const wrapper = setup()
    await flushPromises()
    const latestModels = [{ id: 'added/model', source: 'manual' }]
    mocks.list.mockResolvedValue({ items: [{ ...original, models: latestModels, revision: 2 }] })
    await wrapper.get('[data-testid="model-connection-toggle-existing"]').trigger('click')
    await flushPromises()
    expect(mocks.update).toHaveBeenCalledWith(original.id, expect.objectContaining({ state: 'disabled', models: latestModels }))
    wrapper.unmount()
  })

  it('requires a custom provider identifier, clears the previous preset Base, and saves the typed provider', async () => {
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-add"]').trigger('click')
    await chooseProvider(wrapper, 'deepseek')
    await chooseProvider(wrapper, 'custom')
    await wrapper.get('[data-testid="model-connection-name"]').setValue('Private gateway')
    expect(wrapper.get('[data-testid="model-connection-next"]').attributes('disabled')).toBeDefined()
    await wrapper.get('[data-testid="model-connection-custom-provider"]').setValue('team.gateway')
    await chooseProvider(wrapper, 'anthropic')
    await chooseProvider(wrapper, 'custom')
    expect(wrapper.get('[data-testid="model-connection-custom-provider"]').element).toHaveProperty('value', 'team.gateway')
    expect(wrapper.get('li[aria-current="step"]').text()).toContain('1')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    expect(wrapper.get('li[aria-current="step"]').text()).toContain('2')
    expect(wrapper.get('[data-testid="model-connection-base-url"]').element).toHaveProperty('value', '')
    await wrapper.get('[data-testid="model-connection-base-url"]').setValue('https://team.example.test/v1')
    await chooseCredential(wrapper, key.id)
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    expect(wrapper.get('li[aria-current="step"]').text()).toContain('3')
    expect(wrapper.text()).toContain('team.gateway')
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.create).toHaveBeenCalledWith(expect.objectContaining({ providerId: 'team.gateway', baseUrl: 'https://team.example.test/v1', protocol: 'openai-chat-completions', models: [] }))
    wrapper.unmount()
  })

  it.each(['https://user@models.example.test/v1', 'https://user:password@models.example.test/v1', 'file:///tmp/model-api'])('rejects an API Base containing credentials or an unsupported protocol: %s', async (baseUrl) => {
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-add"]').trigger('click')
    await chooseProvider(wrapper, 'deepseek')
    await wrapper.get('[data-testid="model-connection-name"]').setValue('Private gateway')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await chooseCredential(wrapper, key.id)
    await wrapper.get('[data-testid="model-connection-base-url"]').setValue(baseUrl)
    expect(wrapper.get('[data-testid="model-connection-next"]').attributes('disabled')).toBeDefined()
    expect(mocks.create).not.toHaveBeenCalled()
    await wrapper.get('[data-testid="model-connection-base-url"]').setValue('https://models.example.test/v1')
    expect(wrapper.get('[data-testid="model-connection-next"]').attributes('disabled')).toBeUndefined()
    wrapper.unmount()
  })

  it('retains a custom provider and existing model metadata when editing its service', async () => {
    const service = { id: 'custom-service', name: 'Private API', providerId: 'team.gateway', protocol: 'openai-chat-completions', baseUrl: 'https://team.example.test/v1', credentialId: key.id, auth: { scheme: 'bearer' }, state: 'active', revision: 1, models: [{ id: 'vendor/model', source: 'manual', maxTokens: 4096 }] }
    mocks.list.mockResolvedValue({ items: [service] })
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-edit-custom-service"]').trigger('click')
    expect(wrapper.get('[data-testid="model-connection-custom-provider"]').element).toHaveProperty('value', 'team.gateway')
    await chooseProvider(wrapper, service.providerId)
    await chooseProvider(wrapper, 'custom')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    expect(wrapper.get('[data-testid="model-connection-base-url"]').element).toHaveProperty('value', service.baseUrl)
    await wrapper.get('[data-testid="model-connection-base-url"]').setValue('https://repaired.example.test/v1')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.update).toHaveBeenCalledWith(service.id, expect.objectContaining({ providerId: 'team.gateway', baseUrl: 'https://repaired.example.test/v1', models: service.models }))
    wrapper.unmount()
  })

  it.each(['needs_configuration', 'disabled'])('repairs a legacy %s service with a new Base and key while preserving explicit disablement', async (state) => {
    const service = { id: 'legacy', name: 'Legacy custom service', providerId: 'custom', protocol: 'openai-chat-completions', baseUrl: '', credentialId: 'cleared-key', auth: { scheme: 'bearer' }, state, revision: 1, models: [{ id: 'vendor/legacy-model', source: 'manual' }] }
    mocks.list.mockResolvedValue({ items: [service] })
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-edit-legacy"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-base-url"]').setValue('https://repaired.example.test/v1')
    await chooseCredential(wrapper, key.id)
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.update).toHaveBeenCalledWith('legacy', expect.objectContaining({ baseUrl: 'https://repaired.example.test/v1', credentialId: key.id, state: state === 'disabled' ? 'disabled' : 'active', models: service.models }))
    expect(mocks.create).not.toHaveBeenCalled()
    expect(wrapper.find('[data-testid="model-connection-form"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('creates a reusable connection by credential reference without requiring a model or copying a secret', async () => {
    const wrapper = setup(); await flushPromises(); await fillForm(wrapper)
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click'); await flushPromises()
    expect(mocks.create).toHaveBeenCalledWith(expect.objectContaining({ name: 'Independent model service', protocol: 'openai-chat-completions', credentialId: 'key', models: [] }))
    expect(mocks.create.mock.calls[0][0]).not.toHaveProperty('value')
    expect(mocks.create.mock.calls[0][0]).not.toHaveProperty('toolId')
    expect(wrapper.find('[data-testid="model-connection-form"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('keeps the service draft open after an API error without editing models on the credentials tab', async () => {
    mocks.create.mockRejectedValueOnce(new Error('connection conflict'))
    const wrapper = setup(); await flushPromises(); await fillForm(wrapper)
    expect(wrapper.find('[data-testid="model-connection-models"]').exists()).toBe(false)
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click'); await flushPromises()
    expect(mocks.create).toHaveBeenCalledWith(expect.objectContaining({ name: 'Independent model service', baseUrl: 'https://api.deepseek.com/v1', models: [] }))
    expect(wrapper.text()).toContain('connection conflict')
    expect(wrapper.find('[data-testid="model-connection-form"]').exists()).toBe(true)
    expect(wrapper.get('[data-testid="model-connection-form"]').attributes('data-step')).toBe('3')
    wrapper.unmount()
  })
  it('preserves raw model IDs and their capability metadata while editing only the service address', async () => {
    const service: ModelConnection = { id: 'existing', name: 'Configured service', providerId: 'deepseek', protocol: 'openai-chat-completions', baseUrl: 'https://api.deepseek.com/v1', credentialId: key.id, auth: { scheme: 'bearer' }, state: 'active', revision: 2, models: [{ id: 'vendor/original/model', source: 'manual', input: ['text', 'image'], contextWindow: 128000, maxTokens: 8192 }, { id: 'fast-model', source: 'manual' }] }
    mocks.list.mockResolvedValue({ items: [service] })
    mocks.update.mockRejectedValueOnce(new Error('service update unavailable'))
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-edit-existing"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-base-url"]').setValue('https://models.example.test/v1')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    expect(wrapper.find('[data-testid="model-connection-models"]').exists()).toBe(false)
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.update).toHaveBeenCalledWith(service.id, expect.objectContaining({ baseUrl: 'https://models.example.test/v1', models: service.models }))
    expect(wrapper.text()).toContain('service update unavailable')
    expect(wrapper.find('[data-testid="model-connection-form"]').exists()).toBe(true)
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.update).toHaveBeenCalledTimes(2)
    expect(mocks.update).toHaveBeenLastCalledWith(service.id, expect.objectContaining({ models: service.models }))
    expect(mocks.create).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it.each([
    ['moonshot', 'https://api.moonshot.ai/anthropic'],
    ['zai', 'https://api.z.ai/api/anthropic'],
  ])('offers the %s service preset while retaining an independent key reference', async (provider, baseUrl) => {
    const wrapper = setup()
    await flushPromises()
    await wrapper.get('[data-testid="model-connection-add"]').trigger('click')
    await chooseProvider(wrapper, provider)
    expect(wrapper.getComponent('[data-testid="model-connection-protocol"]').props('modelValue')).toBe('anthropic-messages')
    await wrapper.get('[data-testid="model-connection-name"]').setValue('Regional model service')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    expect(wrapper.get('[data-testid="model-connection-base-url"]').element).toHaveProperty('value', baseUrl)
    await chooseCredential(wrapper, 'key')
    await wrapper.get('[data-testid="model-connection-next"]').trigger('click')
    await wrapper.get('[data-testid="model-connection-save"]').trigger('click')
    await flushPromises()
    expect(mocks.create).toHaveBeenCalledWith(expect.objectContaining({ providerId: provider, baseUrl, protocol: 'anthropic-messages', auth: { scheme: 'bearer' }, credentialId: 'key' }))
    expect(mocks.create.mock.calls[0]![0]).not.toHaveProperty('issuer')
    wrapper.unmount()
  })
})
