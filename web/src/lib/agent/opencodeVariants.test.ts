import { describe, expect, it } from 'vitest'
import { effortChoices, openCodeVariantCatalog, platformVariants, tokenHubVariants } from './fixedEffort'

describe('OpenCode variant catalog', () => {
  it('covers every official model and only the variants OpenCode resolves', () => {
    const models = Object.values(openCodeVariantCatalog)
    const withVariants = models.filter((model) => model.variants.length > 0)
    expect(Object.keys(openCodeVariantCatalog)).toHaveLength(133)
    expect(withVariants).toHaveLength(90)
    expect(models.filter((model) => model.variants.length === 0)).toHaveLength(43)
    expect(platformVariants('opencode/gpt-5.5')).toEqual(['none', 'low', 'medium', 'high', 'xhigh'])
    expect(platformVariants('opencode/gpt-5.6-sol')).toEqual(['none', 'low', 'medium', 'high', 'xhigh', 'max'])
    expect(platformVariants('opencode/gpt-5.5-pro')).toEqual(['medium', 'high', 'xhigh'])
    expect(platformVariants('opencode/deepseek-v4.1-flash')).toEqual(['low', 'high', 'max'])
    expect(platformVariants('opencode/deepseek-v4-pro')).toEqual(['high', 'max'])
    expect(platformVariants('opencode/claude-haiku-4-5')).toEqual(['high', 'max'])
    expect(platformVariants('opencode/claude-haiku-5-5')).toEqual(['none', 'low', 'medium', 'high', 'xhigh', 'max'])
    expect(platformVariants('opencode/qwen3.5-plus')).toEqual(['none', 'high', 'max'])
    expect(platformVariants('opencode/qwen3.8-max')).toEqual(['low', 'medium', 'xhigh'])
    expect(platformVariants('opencode/minimax-m3-free')).toEqual(['none', 'thinking'])
    expect(platformVariants('opencode/minimax-m3')).toEqual([])
    expect(platformVariants('opencode/glm-4.6')).toEqual([])
    expect(platformVariants('opencode/kimi-k2.5')).toEqual([])
    expect(platformVariants('opencode/kimi-k2.7-code')).toEqual([])
    expect(tokenHubVariants('deepseek-v4-flash')).toEqual(['low', 'high', 'max'])
    expect(tokenHubVariants('deepseek-v4-pro')).toEqual(['low', 'high', 'max'])
    expect(effortChoices('opencode', 'platform', undefined, undefined, 'opencode/deepseek-v4-pro')).toEqual(['high', 'max'])
    expect(effortChoices('opencode', 'connection', 'tokenhub', 'https://tokenhub.tencentmaas.com/v1', 'deepseek-v4-pro')).toEqual(['low', 'high', 'max'])
    expect(effortChoices('opencode', 'connection', '', 'https://tokenhub.tencentmaas.com/v1', 'deepseek-v4-pro')).toEqual(['low', 'high', 'max'])
    expect(effortChoices('opencode', 'connection', '', 'https://tokenhub.tencentmaas.com.evil.example/v1', 'deepseek-v4-pro')).toEqual([])
    expect(effortChoices('opencode', 'connection', 'other', 'https://models.example/v1', 'deepseek-v4-pro')).toEqual([])
    expect(effortChoices('cursor', 'platform', undefined, undefined, 'gpt-5.5')).toEqual([])
    expect(effortChoices('codex', 'platform', undefined, undefined, 'gpt-5.5')).toEqual([])
    expect(effortChoices('deepseek_harness', 'connection', 'tokenhub', '', 'deepseek-v4-flash')).toEqual([])
    expect(effortChoices('claude_code', 'platform', undefined, undefined, 'claude-haiku-4-5')).toEqual([])
    expect(effortChoices('codebuddy', 'platform', undefined, undefined, 'gpt-5.5')).toEqual([])
    expect(effortChoices('trae', 'platform', undefined, undefined, 'gpt-5.5')).toEqual([])
  })
})
