// @vitest-environment happy-dom
import { ref } from 'vue'
import { flushPromises, mount } from '@vue/test-utils'
import { createRouter, createMemoryHistory } from 'vue-router'
import { createI18n } from 'vue-i18n'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import nav from '@/locales/zh-CN/nav.json'
import common from '@/locales/zh-CN/common.json'
import pages from '@/locales/zh-CN/pages.json'
const mocks = vi.hoisted(() => {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { ref } = require('vue') as typeof import('vue')
  return { workspace: ref({ name: 'Workspace', description: '', variables: [] }), isMobile: ref(false), listWorkflows: vi.fn(), getWorkflow: vi.fn(), deleteWorkflow: vi.fn(), patchWorkflowHomeVisibility: vi.fn(), patchWorkflowNotifyPolicy: vi.fn(), triggerImport: vi.fn(), error: vi.fn() }
})
vi.mock('@/lib/api/api', () => ({ api: mocks }))
vi.mock('@/lib/composables/useWorkspaceContext', () => ({ useWorkspaceContext: () => ({ workspace: mocks.workspace, ensureLoaded: async () => mocks.workspace.value }) }))
vi.mock('@/lib/composables/useToast', () => ({ useToast: () => ({ success: vi.fn(), error: mocks.error, warn: vi.fn() }) }))
vi.mock('@/lib/composables/useBreakpoint', () => ({ useBreakpoint: () => ({ isMobile: mocks.isMobile }) }))
vi.mock('@/lib/run/useWorkflowFavorites', () => ({ useWorkflowFavorites: () => ({ isFavorite: () => false, toggleFavorite: vi.fn() }) }))
vi.mock('@/lib/run/useWorkflowImport', () => ({ useWorkflowImport: () => ({ fileInput: ref(null), triggerImport: mocks.triggerImport, handleFileChange: vi.fn() }) }))
import { workflowCatalogRevision } from '@/lib/api/workflowCatalogEvents'
import WorkflowsView from './WorkflowsView.vue'
const head = { id: 'wf-one', name: 'Draft one', description: 'First workflow', status: 'draft', version: 3, publishedVersion: 2, nodes: [{ id: 'input', type: 'input', config: { variables: [{ name: 'current', ask: true, required: true, value: 'head value' }] } }], edges: [], updatedAt: '2026-10-20', showOnHome: false }
async function setup() {
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: '/:pathMatch(.*)*', component: { template: '<div />' } }] })
  await router.push('/workflows')
  const i18n = createI18n({ legacy: false, locale: 'zh-CN', messages: { 'zh-CN': { ...nav, ...common, ...pages } } })
  const wrapper = mount(WorkflowsView, { global: { plugins: [router, i18n], directives: { 'hover-ink': {} }, stubs: { WorkspacePage: { template: '<section><slot /></section>' }, RunLaunchModal: { name: 'RunLaunchModal', props: ['workflowId', 'fields', 'runInputs', 'publishedSnapshot'], template: '<div data-testid="launch" />' }, CopyWorkflowModal: true, ExportVersionModal: true } } })
  await flushPromises()
  return { wrapper, router }
}
beforeEach(() => { vi.clearAllMocks(); localStorage.clear(); mocks.isMobile.value = false; mocks.listWorkflows.mockResolvedValue([head]); mocks.getWorkflow.mockResolvedValue(head) })
describe('workspace workflow management', () => {
  it('searches in the management page while preserving direct editing with a clean URL', async () => {
    const { wrapper, router } = await setup()
    expect(wrapper.text()).toContain('Draft one')
    await wrapper.get('input[type="search"]').setValue('unmatched')
    expect(wrapper.text()).toContain('没有匹配的工作流')
    expect(wrapper.get('[data-testid="workflows-empty"]').attributes('data-empty-kind')).toBe('search')
    await wrapper.get('[data-testid="workflows-empty"] button').trigger('click')
    const name = wrapper.findAll('tr').find((row) => row.text().includes('Draft one'))!
    await name.trigger('click')
    await flushPromises()
    expect(router.currentRoute.value.fullPath).toBe('/workflows/wf-one/edit')
    wrapper.unmount()
  })
  it('manual runs load the current saved head and seed its own ask fields', async () => {
    const { wrapper } = await setup()
    await wrapper.findAll('button').find((button) => button.text() === '运行')!.trigger('click')
    await flushPromises()
    expect(mocks.getWorkflow).toHaveBeenCalledWith('wf-one')
    const launch = wrapper.findComponent({ name: 'RunLaunchModal' })
    expect(launch.props('workflowId')).toBe('wf-one')
    expect(launch.props('fields')).toEqual([expect.objectContaining({ key: 'current', default: 'head value' })])
    expect(launch.props('publishedSnapshot')).not.toBe(true)
    wrapper.unmount()
  })
  it('shows failures instead of treating a failed list as a genuine empty workspace', async () => {
    mocks.listWorkflows.mockRejectedValueOnce(new Error('Directory offline'))
    const { wrapper } = await setup()
    expect(wrapper.get('[role="alert"]').text()).toContain('Directory offline')
    await wrapper.get('[role="alert"] button').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('Draft one')
    wrapper.unmount()
  })
  it('keeps desktop rows compact and places secondary actions in an accessible menu', async () => {
    const { wrapper } = await setup()
    const actions = wrapper.get('[data-testid="wf-actions-group"]')
    expect(actions.findAll('button')).toHaveLength(3)
    const more = actions.get('[aria-haspopup="menu"]')
    await more.trigger('click')
    expect(more.attributes('aria-expanded')).toBe('true')
    const menu = document.querySelector('[role="menu"]')!
    expect(menu.textContent).toContain('收藏')
    expect(menu.textContent).toContain('复制')
    expect(menu.textContent).toContain('导出')
    expect(menu.textContent).toContain('删除')
    document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' }))
    await flushPromises()
    expect(document.querySelector('[role="menu"]')).toBeNull()
    wrapper.unmount()
  })
  it('offers create and import actions for a genuine empty workspace', async () => {
    mocks.listWorkflows.mockResolvedValueOnce([])
    const { wrapper, router } = await setup()
    const empty = wrapper.get('[data-testid="workflows-empty"]')
    expect(empty.attributes('data-empty-kind')).toBe('workspace')
    expect(empty.text()).toContain('暂无工作流')
    const buttons = empty.findAll('button')
    await buttons.find((button) => button.text() === '导入')!.trigger('click')
    expect(mocks.triggerImport).toHaveBeenCalledOnce()
    await buttons.find((button) => button.text() === '新建工作流')!.trigger('click')
    await flushPromises()
    expect(router.currentRoute.value.path).toBe('/workflows/new/edit')
    wrapper.unmount()
  })
  it('replaces the empty workspace with the default workflow when the catalog revision advances', async () => {
    mocks.listWorkflows.mockResolvedValueOnce([])
    const { wrapper } = await setup()
    expect(wrapper.get('[data-testid="workflows-empty"]').text()).toContain('暂无工作流')
    mocks.listWorkflows.mockResolvedValue([{ ...head, id: 'wf-default', name: '默认工作流', status: 'published', showOnHome: true }])
    workflowCatalogRevision.value++
    await flushPromises()
    expect(wrapper.text()).toContain('默认工作流')
    expect(wrapper.find('[data-testid="workflows-empty"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('keeps notification mode compact and reveals custom events only when editing them', async () => {
    mocks.patchWorkflowNotifyPolicy.mockImplementation(async (_id, notifyPolicy) => ({ ...head, notifyPolicy }))
    const { wrapper, router } = await setup()
    const select = wrapper.get('[data-testid="wf-notify-mode"] [data-test="app-select-trigger"]')
    expect(select.attributes('aria-label')).toContain('Draft one')
    expect(wrapper.find('[data-testid="wf-notify-events"]').exists()).toBe(false)
    await select.trigger('click')
    ;(document.querySelector('[data-test="app-select-option-inherit"]') as HTMLButtonElement).click()
    await flushPromises()
    expect(mocks.patchWorkflowNotifyPolicy).not.toHaveBeenCalled()
    await select.trigger('click')
    ;(document.querySelector('[data-test="app-select-option-custom"]') as HTMLButtonElement).click()
    await flushPromises()
    expect(mocks.patchWorkflowNotifyPolicy).toHaveBeenLastCalledWith('wf-one', { mode: 'custom', events: ['waiting_human', 'failed'] })
    const events = wrapper.get('[data-testid="wf-notify-events"]')
    expect(events.findAll('input[type="checkbox"]')).toHaveLength(3)
    await events.findAll('input[type="checkbox"]')[2].setValue(true)
    await flushPromises()
    expect(mocks.patchWorkflowNotifyPolicy).toHaveBeenLastCalledWith('wf-one', { mode: 'custom', events: ['waiting_human', 'failed', 'completed'] })
    await wrapper.get('[data-testid="wf-notify-edit-events"]').trigger('click')
    expect(wrapper.find('[data-testid="wf-notify-events"]').exists()).toBe(false)
    await select.trigger('click')
    ;(document.querySelector('[data-test="app-select-option-off"]') as HTMLButtonElement).click()
    await flushPromises()
    expect(mocks.patchWorkflowNotifyPolicy).toHaveBeenLastCalledWith('wf-one', { mode: 'off', events: ['waiting_human', 'failed', 'completed'] })
    expect(router.currentRoute.value.path).toBe('/workflows')
    wrapper.unmount()
  })
  it('labels inherited notifications by their source when a workflow carries its own defaults', async () => {
    const migrated = { ...head, id: 'wf-migrated', name: 'Migrated', defaults: { inheritWorkspace: false, variables: [], notifyPolicy: { enabled: true, channelIds: ['chn-b'] } } }
    mocks.listWorkflows.mockResolvedValueOnce([head, migrated])
    const { wrapper } = await setup()
    const triggers = wrapper.findAll('[data-testid="wf-notify-mode"] [data-test="app-select-trigger"]')
    expect(triggers[0].text()).toContain('跟随工作区')
    expect(triggers[1].text()).toContain('跟随工作流默认')
    wrapper.unmount()
  })
  it('keeps mobile visibility controls and the same three row actions', async () => {
    mocks.isMobile.value = true
    mocks.patchWorkflowHomeVisibility.mockImplementation(async (_id, showOnHome) => ({ ...head, showOnHome }))
    const { wrapper } = await setup()
    expect(wrapper.find('[data-testid="wf-notify-inline"]').exists()).toBe(true)
    expect(wrapper.find('[data-testid="wf-home-visibility-inline"]').exists()).toBe(true)
    const actions = wrapper.get('[data-testid="wf-actions-group"]')
    expect(actions.findAll('button')).toHaveLength(3)
    const home = wrapper.get('[data-testid="wf-home-visibility-switch"]')
    await home.trigger('click')
    await flushPromises()
    expect(mocks.patchWorkflowHomeVisibility).toHaveBeenCalledWith('wf-one', true)
    expect(home.attributes('aria-checked')).toBe('true')
    await actions.get('[aria-haspopup="menu"]').trigger('click')
    expect(document.querySelector('[role="menu"]')?.textContent).toContain('收藏')
    wrapper.unmount()
  })
  it('disables the themed selector during saving and keeps the persisted mode when the request fails', async () => {
    let failSave!: (reason: Error) => void
    mocks.patchWorkflowNotifyPolicy.mockReturnValueOnce(new Promise((_, reject) => { failSave = reject }))
    const { wrapper, router } = await setup()
    const trigger = wrapper.get('[data-testid="wf-notify-mode"] [data-test="app-select-trigger"]')
    await trigger.trigger('click')
    ;(document.querySelector('[data-test="app-select-option-custom"]') as HTMLButtonElement).click()
    await flushPromises()
    expect(trigger.attributes('disabled')).toBeDefined()
    expect(document.querySelector('[role="listbox"]')).toBeNull()
    expect(trigger.text()).toContain('跟随工作区')
    await trigger.trigger('click')
    expect(document.querySelector('[role="listbox"]')).toBeNull()
    expect(mocks.patchWorkflowNotifyPolicy).toHaveBeenCalledOnce()
    failSave(new Error('Notification save failed'))
    await flushPromises()
    expect(trigger.attributes('disabled')).toBeUndefined()
    expect(trigger.text()).toContain('跟随工作区')
    expect(wrapper.find('[data-testid="wf-notify-events"]').exists()).toBe(false)
    expect(mocks.error).toHaveBeenCalledWith('Notification save failed')
    expect(router.currentRoute.value.path).toBe('/workflows')
    wrapper.unmount()
  })
  it('insets the name column 12px from the hover row and keeps the last column flush', async () => {
    const { readFileSync } = await import('node:fs')
    const { dirname, join } = await import('node:path')
    const { fileURLToPath } = await import('node:url')
    const src = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'WorkflowsView.vue'), 'utf8')
    const style = src.match(/<style scoped>([\s\S]*?)<\/style>/)?.[1] ?? ''
    const rule = (selector: string) => {
      const found = style.match(new RegExp(`${selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\{[^}]*\\}`))?.[0]
      expect(found, selector).toBeTruthy()
      return found!
    }
    expect(style).not.toMatch(/th:first-child|td:first-child/)
    expect(style).not.toMatch(/padding-left:\s*0/)
    const headerRule = rule('.workflow-directory th')
    const cellRule = rule('.workflow-directory td')
    const lastRule = rule('.workflow-directory th:last-child, .workflow-directory td:last-child')
    const toolbarRule = rule('.workflow-toolbar')
    const nameRule = rule('.workflow-name')
    expect(headerRule).toMatch(/padding:\s*0 12px/)
    expect(cellRule).toMatch(/padding:\s*15px 12px/)
    expect(lastRule).toMatch(/padding-right:\s*0/)
    expect(toolbarRule).toMatch(/padding:\s*4px 0 18px/)
    expect(style).toContain('.workflow-row:hover { background: rgb(var(--c-txt) / .018); }')
    expect(style).toMatch(/@container workflow-directory \(max-width:\s*740px\) \{[\s\S]*?\.workflow-row \{[^}]*padding:\s*16px 0 16px 12px;/)
    expect(style).not.toMatch(/\.workflow-search \{[^}]*margin-left/)
    expect(src).toContain('<WorkspacePage title-key="nav.workflows" description-key="nav.workflowsHint">')

    const described = { ...head, id: 'wf-desc', name: '自我迭代', description: '持续改进自身流程' }
    const plain = { ...head, id: 'wf-plain', name: '无描述流程', description: '' }
    const longName = { ...head, id: 'wf-long', name: '超长工作流名称'.repeat(12), description: '超长描述会在名称同一左缘省略'.repeat(8) }
    mocks.listWorkflows.mockResolvedValueOnce([described, plain, longName])
    const { wrapper } = await setup()
    const sheet = document.createElement('style')
    sheet.textContent = [headerRule, cellRule, lastRule, toolbarRule, nameRule].join('\n')
    document.head.appendChild(sheet)
    document.body.appendChild(wrapper.element)
    const table = wrapper.get('[data-testid="workflows-desktop-table"]')
    const nameHeader = table.findAll('thead th')[0]
    const nameCells = table.findAll('.workflow-name-cell')
    const actionCell = table.get('[data-testid="wf-actions-cell"]')
    expect(nameHeader.text()).toBe('名称')
    expect(getComputedStyle(nameHeader.element).paddingLeft).toBe('12px')
    expect(nameCells).toHaveLength(3)
    const namePadding = nameCells.map((cell) => getComputedStyle(cell.element).paddingLeft)
    expect(namePadding).toEqual(['12px', '12px', '12px'])
    expect(table.findAll('.workflow-description')).toHaveLength(2)
    expect(nameCells[1].find('.workflow-description').exists()).toBe(false)
    expect(getComputedStyle(actionCell.element).paddingRight).toBe('0px')
    expect(getComputedStyle(table.findAll('thead th').at(-1)!.element).paddingRight).toBe('0px')
    expect(getComputedStyle(wrapper.get('.workflow-toolbar').element).paddingLeft).toBe('0px')
    const longButton = nameCells[2].get('.workflow-name')
    expect(longButton.text()).toContain('超长工作流名称')
    expect(getComputedStyle(longButton.element).textOverflow).toBe('ellipsis')
    expect(getComputedStyle(longButton.element).overflow).toBe('hidden')
    sheet.remove()
    wrapper.unmount()
  })
})
