// Builds the Live variants overlay and copies it next to every preview-pick.js
// copy (web/public, server handlers, sandbox-gateway preview inject).
import { execFileSync } from 'node:child_process'
import { copyFileSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = join(dirname(fileURLToPath(import.meta.url)), '..')
const repo = join(web, '..')
const outDir = join(web, 'dist-live-overlay')

execFileSync('npx', ['vite', 'build', '--config', 'vite.liveoverlay.config.ts', '--logLevel', 'warn'], {
  cwd: web,
  stdio: 'inherit',
})

const header = '/* Grasp Live variants overlay. Generated by web/scripts/build-live-overlay.mjs from web/src/liveoverlay; do not edit. */\n'
const body = readFileSync(join(outDir, 'live-overlay.js'), 'utf8')
const bundle = join(web, 'public', 'live-overlay.js')
writeFileSync(bundle, header + body)
rmSync(outDir, { recursive: true, force: true })

for (const dest of [
  join(repo, 'server', 'internal', 'handlers', 'live-overlay.js'),
  join(repo, 'sandbox-gateway', 'sandbox', 'internal', 'previewinject', 'live-overlay.js'),
]) {
  copyFileSync(bundle, dest)
}
console.log('live-overlay.js written to 3 locations')
