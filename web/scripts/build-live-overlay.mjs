// Builds the Live variants overlay and copies it next to every preview-pick.js
// copy (web/public, server handlers, sandbox-gateway preview inject).
import { execFileSync } from 'node:child_process'
import { copyFileSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { build } from 'vite'
import { fileURLToPath } from 'node:url'

const web = join(dirname(fileURLToPath(import.meta.url)), '..')
const repo = join(web, '..')
const outDir = join(web, 'dist-live-overlay')
const cleanGenerated = (text) => text.replace(/[ \t]+$/gm, '')

// The native pages and injected toolbar use the same catalog as the Vue app.
// Bundle the DOM adapter so the sandbox runtime needs no package loader.
const iconEntry = join(web, 'src/lib/icons/runtime.ts')
async function bundleIcons(format) {
  const result = await build({
    root: web,
    configFile: false,
    logLevel: 'warn',
    build: {
      write: false,
      minify: 'esbuild',
      target: 'es2020',
      lib: { entry: iconEntry, name: 'GraspRuntimeIcons', formats: [format], fileName: 'icons' },
      rollupOptions: { output: { inlineDynamicImports: true } },
    },
  })
  const outputs = (Array.isArray(result) ? result : [result]).flatMap((item) => item.output)
  const chunk = outputs.find((item) => item.type === 'chunk')
  if (!chunk) throw new Error(`Missing ${format} native icon bundle`)
  return cleanGenerated(chunk.code)
}
const moduleCode = await bundleIcons('es')
const moduleHeader = '/* Shared Grasp icon runtime. Generated by web/scripts/build-live-overlay.mjs; do not edit. */\n'
writeFileSync(join(repo, 'sandbox-gateway/sandbox/web/static/js/ui/icons.js'), moduleHeader + moduleCode)
const inlineCode = await bundleIcons('iife')
const pickPath = join(web, 'public/preview-pick.js')
const pickSource = readFileSync(pickPath, 'utf8')
const iconMarker = /  \/\/ BEGIN SHARED ICON RUNTIME[^\n]*\n[\s\S]*?  \/\/ END SHARED ICON RUNTIME/
if (!iconMarker.test(pickSource)) throw new Error('preview-pick.js shared icon runtime markers missing')
writeFileSync(pickPath, pickSource.replace(iconMarker, () =>
  '  // BEGIN SHARED ICON RUNTIME (generated by build:live-overlay)\n' +
  '/* eslint-disable @typescript-eslint/no-unused-expressions -- Generated bundle; source is linted separately. */\n' +
  inlineCode + '/* eslint-enable @typescript-eslint/no-unused-expressions */\n  // END SHARED ICON RUNTIME'))
for (const dest of [
  join(repo, 'server/internal/handlers/preview-pick.js'),
  join(repo, 'sandbox-gateway/sandbox/internal/previewinject/preview-pick.js'),
]) copyFileSync(pickPath, dest)
console.log('shared icon runtime and preview-pick.js written to native/injected pages')

execFileSync('npx', ['vite', 'build', '--config', 'vite.liveoverlay.config.ts', '--logLevel', 'warn'], {
  cwd: web,
  stdio: 'inherit',
})

const header = '/* Grasp Live variants overlay. Generated by web/scripts/build-live-overlay.mjs from web/src/liveoverlay; do not edit. */\n'
const body = readFileSync(join(outDir, 'live-overlay.js'), 'utf8')
const bundle = join(web, 'public', 'live-overlay.js')
writeFileSync(bundle, header + cleanGenerated(body))
rmSync(outDir, { recursive: true, force: true })

for (const dest of [
  join(repo, 'server', 'internal', 'handlers', 'live-overlay.js'),
  join(repo, 'sandbox-gateway', 'sandbox', 'internal', 'previewinject', 'live-overlay.js'),
]) {
  copyFileSync(bundle, dest)
}
console.log('live-overlay.js written to 3 locations')
