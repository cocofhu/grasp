// Builds the page-control executor and copies it next to every preview-pick.js
// copy (web/public, server handlers, sandbox-gateway preview inject).
import { execFileSync } from 'node:child_process'
import { copyFileSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = join(dirname(fileURLToPath(import.meta.url)), '..')
const repo = join(web, '..')
const outDir = join(web, 'dist-page-control')

execFileSync('npx', ['vite', 'build', '--config', 'vite.pagecontrol.config.ts', '--logLevel', 'warn'], {
  cwd: web,
  stdio: 'inherit',
})

const header =
  '/* Grasp page-control executor. Generated by web/scripts/build-page-control.mjs from web/src/pagecontrol; do not edit.\n' +
  ' * Bundles @page-agent/page-controller (MIT, Copyright (c) Alibaba Group Holding Limited). */\n'
const body = readFileSync(join(outDir, 'page-control.js'), 'utf8')
const bundle = join(web, 'public', 'page-control.js')
writeFileSync(bundle, header + body)
rmSync(outDir, { recursive: true, force: true })

for (const dest of [
  join(repo, 'server', 'internal', 'handlers', 'page-control.js'),
  join(repo, 'sandbox-gateway', 'sandbox', 'internal', 'previewinject', 'page-control.js'),
]) {
  copyFileSync(bundle, dest)
}
console.log('page-control.js written to 3 locations')
